const STRINGS = { en, kn };

export function translate(lang, key, vars, fallback) {
  let text = STRINGS[lang]?.[key] ?? en[key] ?? fallback ?? key;
  for (const [name, value] of Object.entries(vars || {})) {
    text = text.replaceAll(`{${name}}`, value ?? "");
  }
  return text;
}

export const LanguageContext = createContext("en");

// t(key, vars, fallback); t.lang is the current language code
export function useT() {
  const lang = useContext(LanguageContext);
  const t = (key, vars, fallback) => translate(lang, key, vars, fallback);
  t.lang = lang;
  return t;
}
